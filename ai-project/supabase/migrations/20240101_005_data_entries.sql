-- Create data_entries table
create table public.data_entries (
  id integer generated by default as identity primary key,
  purchase_code text not null,
  installcode text,
  license_type text,
  env_info text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  req_route text
);

-- Enable RLS
alter table public.data_entries enable row level security;

-- Policy: Users can read own data entries
create policy "Users can view own data entries"
  on public.data_entries for select
  using ( true );